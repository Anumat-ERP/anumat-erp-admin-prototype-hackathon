/** Deterministic members, so the demo looks the same on every visit. */
function members(seed: number, count: number, domain: string, activeDays: number[]): Member[] {
  return Array.from({ length: count }, (_, i) => {
    const first = FIRST[(seed * 7 + i * 3) % FIRST.length]!;
    const last = LAST[(seed * 5 + i * 7) % LAST.length]!;
    return {
      id: `${domain}-m${i + 1}`,
      name: `${first} ${last}`,
      email: `${first.toLowerCase()}.${last.toLowerCase()}@${domain}.example`,
      access: i === 0 ? 'owner' : i === 1 ? 'admin' : 'member',
      department: DEPTS[(seed + i) % DEPTS.length]!,
      lastSeenAt: at(-(activeDays[i % activeDays.length] ?? 1), 9 + (i % 8), (i * 13) % 60),
    };
  });
}

/** Named people, so the console matches the customer prototype. */
function named(domain: string, people: [string, Member['access'], string, number][]): Member[] {
  return people.map(([name, access, department, days], i) => ({
    id: `${domain}-m${i + 1}`,
    name,
    email: `${name.split(' ')[0]!.toLowerCase()}@${domain}.example`,
    access,
    department,
    lastSeenAt: at(-days, 9 + (i % 8), (i * 13) % 60),
  }));
}

