/** An ISO timestamp `days` from now (negative = past), at `hour`. */
export function at(days: number, hour = 10, minute = 0) {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

